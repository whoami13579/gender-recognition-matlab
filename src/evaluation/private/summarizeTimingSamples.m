function timing = summarizeTimingSamples(samples, warmupRuns, batchSize)
%SUMMARIZETIMINGSAMPLES Build timing statistics in seconds.
timing = struct('SamplesSeconds', samples, 'WarmupRuns', warmupRuns, ...
    'NumRepeats', numel(samples), 'MedianSeconds', median(samples), ...
    'MeanSeconds', mean(samples), 'StdSeconds', std(samples, 0), ...
    'MinSeconds', min(samples), 'MaxSeconds', max(samples), 'BatchSize', batchSize, ...
    'SecondsPerSample', [], 'MeanSecondsPerSample', []);
if ~isempty(batchSize)
    timing.SecondsPerSample = timing.MedianSeconds / batchSize;
    timing.MeanSecondsPerSample = timing.MeanSeconds / batchSize;
end
end
