function [images, index, report] = loadImages(path)
% Aggregate integrity and a private, filename-free exact-content index.
[images, labels, subjects, samples] = loadDataset(path);
[fingerprint, hashes] = fingerprintDecodedDataset(images, samples);
index = struct('Hashes', hashes, 'Labels', labels, 'Subjects', subjects);
[~, first, groups] = unique(subjects);
counts = accumarray(groups, 1);
matches = triu(hashes == hashes.', 1);
report = struct('NumImages', numel(images), 'ClassCounts', [nnz(labels == 0) nnz(labels == 1)], ...
    'UniqueSampleCount', height(samples), 'SubjectCounts', [nnz(labels(first) == 0) nnz(labels(first) == 1)], ...
    'ImagesPerSubjectValues', unique(counts).', 'ImageShapes', ...
    unique([samples.Height samples.Width samples.Channels], 'rows'), ...
    'PixelTypes', unique(samples.PixelType).', 'DecodedSHA256', fingerprint, ...
    'DuplicateSamplePairs', nnz(matches), 'DuplicateCrossSubjectPairs', nnz(matches & (subjects ~= subjects.')), ...
    'ConflictingLabelPairs', nnz(matches & (labels ~= labels.')));
end
