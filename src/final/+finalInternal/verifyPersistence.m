function [verification, reloaded] = verifyPersistence(pipeline, images, modelPath)
initialRNG = rng;
[before, a] = predictPipeline(pipeline, images);
savePipelineModel(pipeline, modelPath);
reloaded = loadPipelineModel(modelPath);
[after, b] = predictPipeline(reloaded, images);
scale = max(abs(a), abs(b));
delta = abs(a - b);
% Eight representable steps at each score's own magnitude. No unit-scale
% absolute floor, so very small scores cannot hide a large relative change.
toleranceULPs = 8;
[~, order] = sort(a);
[~, reloadOrder] = sort(b);
verification = struct('Method', pipeline.Method, 'BatchSize', numel(images), ...
    'LabelsEqual', isequal(before, after), 'FittedStateEqual', isequaln(pipeline, reloaded), ...
    'ScoresExactlyEqual', isequal(a, b), 'ScoreOrderEqual', ...
    isequal(order, reloadOrder) && isequal(diff(a(order)) == 0, diff(b(order)) == 0), ...
    'ScoresFinite', all(isfinite(a) & isfinite(b)), 'ToleranceULPs', toleranceULPs, ...
    'MaxAbsoluteDifference', max(delta), 'MaxRelativeDifference', max([0; delta(scale > 0) ./ scale(scale > 0)]), ...
    'RNGUnchanged', isequal(initialRNG, rng));
assert(verification.LabelsEqual && verification.FittedStateEqual && verification.ScoreOrderEqual && ...
    verification.ScoresFinite && all(delta <= toleranceULPs * eps(scale)) && verification.RNGUnchanged, ...
    'genderRecognition:PersistenceMismatch', 'Save and reload verification failed for %s.', pipeline.Method);
end
