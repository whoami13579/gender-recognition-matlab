function [pipelines, manifest, frozen, metadata, index, comparison] = readBundle(directory)
directory = finalInternal.resolvePath(directory);
assert(~endsWith(directory, ".incomplete") && isfolder(directory), ...
    'genderRecognition:FinalArtifactInvalid', 'Expected a completed local training run directory.');
manifest = jsondecode(fileread(fullfile(directory, "model-manifest.json")));
assert(isequal(manifest.SchemaVersion, 1) && isequal(manifest.ModelFormatVersion, 1), ...
    'genderRecognition:UnsupportedPipelineVersion', 'Unsupported final model bundle version.');
frozen = readCheckedJSON(directory, "frozen-configurations.json", manifest.FrozenFileSHA256);
metadata = readCheckedJSON(directory, "training-metadata.json", manifest.TrainingMetadataSHA256);
verification = readCheckedJSON(directory, "persistence-verification.json", manifest.VerificationFileSHA256);
methods = ["pca-bayes", "lda-bayes", "pca-mlp", "lda-mlp"];
assert(isequal(frozen.SchemaVersion, 1) && isequal(metadata.SchemaVersion, 1) && ...
    string(metadata.Status) == "complete" && string(metadata.PersistenceStatus) == "verified" && ...
    isequal(frozen.Synthetic, metadata.Synthetic) && (frozen.Synthetic || frozen.TrainingSamples == 200) && ...
    isequal(frozen.TrainingDecodedSHA256, manifest.TrainingDecodedSHA256) && ...
    isequal(frozen.RepositoryRevision, manifest.RepositoryRevision) && ...
    isequal(frozen.MATLABVersion, manifest.MATLABVersion) && ...
    isequal(frozen.SelectionProvenance, manifest.SelectionProvenance) && ...
    isequal(frozen.Threshold, 0) && isequal(frozen.PositiveClass, 1) && ...
    string(frozen.DecisionRule) == "score > 0" && ...
    finalInternal.checksum(frozen.Configurations, false) == string(frozen.ConfigurationSHA256) && ...
    hasMethods(manifest.Models, methods) && hasMethods(frozen.Configurations, methods) && ...
    hasMethods(metadata.Results, methods) && hasMethods(verification, methods) && ...
    numel(frozen.EffectiveConfigurations) == numel(methods) && all([verification.LabelsEqual]) && ...
    all([verification.FittedStateEqual]) && all([verification.ScoreOrderEqual]) && ...
    all([verification.ScoresFinite]) && all([verification.RNGUnchanged]), ...
    'genderRecognition:FinalArtifactInvalid', 'The training, freeze, and verification manifests disagree.');
initialRNG = rng;
for k = 1:numel(methods)
    model = manifest.Models(k);
    expectedFile = methods(k) + ".mat";
    assert(string(model.File) == expectedFile, 'genderRecognition:FinalArtifactInvalid', ...
        'Unexpected model filename for %s.', methods(k));
    modelPath = fullfile(directory, "models", expectedFile);
    checkFile(modelPath, model.SHA256);
    pipeline = loadPipelineModel(modelPath);
    if iscell(frozen.EffectiveConfigurations)
        effective = frozen.EffectiveConfigurations{k};
    else
        effective = frozen.EffectiveConfigurations(k);
    end
    assert(pipeline.Method == methods(k) && pipeline.NumTrainingSamples == frozen.TrainingSamples && ...
        pipeline.NumTrainingSamples == metadata.Results(k).NumTrainingSamples && ...
        isequal(pipeline.Parameters, metadata.Results(k).Parameters) && ...
        isequal(jsondecode(jsonencode(pipeline.Configuration)), effective), ...
        'genderRecognition:FrozenConfigurationMismatch', 'The loaded %s model differs from the frozen bundle.', methods(k));
    pipelines(k) = pipeline; %#ok<AGROW>
end
assert(isequal(initialRNG, rng), 'genderRecognition:FinalRNGChanged', 'Model loading changed the global RNG.');
if nargout > 4
    indexPath = fullfile(directory, "training-content-index.mat");
    checkFile(indexPath, manifest.TrainingIndexSHA256);
    content = load(indexPath, 'index', '-mat');
    index = content.index;
    assert(isstring(index.Hashes) && all(strlength(index.Hashes) == 64) && ...
        numel(index.Hashes) == frozen.TrainingSamples && numel(index.Labels) == frozen.TrainingSamples && ...
        numel(index.Subjects) == frozen.TrainingSamples && all(ismember(index.Labels, [0 1])), ...
        'genderRecognition:FinalArtifactInvalid', 'Invalid training content index.');
end
if nargout > 5
    comparison = readCheckedJSON(directory, "cv-comparison.json", manifest.CVComparisonSHA256);
end
end

function valid = hasMethods(rows, methods)
valid = isstruct(rows) && isfield(rows, 'Method') && isequal(string({rows.Method}), methods);
end

function data = readCheckedJSON(directory, name, checksum)
path = fullfile(directory, name);
checkFile(path, checksum);
data = jsondecode(fileread(path));
end

function checkFile(path, expected)
[~, name, extension] = fileparts(path);
assert(isfile(path) && finalInternal.checksum(path, true) == string(expected), ...
    'genderRecognition:FinalArtifactInvalid', 'A required bundle file is missing or has a checksum mismatch (%s%s).', ...
    name, extension);
end
